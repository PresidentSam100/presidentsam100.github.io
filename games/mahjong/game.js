  // ---- the turtle -----------------------------------------------------------
  function turtlePositions() {
    var P = [], x, y;
    var rows = [[1, 12], [3, 10], [2, 11], [1, 12], [1, 12], [2, 11], [3, 10], [1, 12]];
    for (y = 0; y < 8; y++) for (x = rows[y][0]; x <= rows[y][1]; x++) P.push([x * 2, y * 2, 0]);
    P.push([0, 7, 0]);            // the head
    P.push([26, 7, 0]);           // the tail
    P.push([28, 7, 0]);           //   and its tip
    for (y = 1; y <= 6; y++) for (x = 4; x <= 9; x++) P.push([x * 2, y * 2, 1]);
    for (y = 2; y <= 5; y++) for (x = 5; x <= 8; x++) P.push([x * 2, y * 2, 2]);
    for (y = 3; y <= 4; y++) for (x = 6; x <= 7; x++) P.push([x * 2, y * 2, 3]);
    P.push([13, 7, 4]);           // the apex
    return P;                     // 144 positions
  }

  function overlaps(a, b) { return Math.abs(a[0] - b[0]) < 2 && Math.abs(a[1] - b[1]) < 2; }
  // free w.r.t. a Set of live indices into pos[]
  function isFree(pos, i, live) {
    var p = pos[i], j, q;
    var leftHit = false, rightHit = false;
    for (j = 0; j < pos.length; j++) {
      if (j === i || !live.has(j)) continue;
      q = pos[j];
      if (q[2] > p[2] && overlaps(p, q)) return false;               // capped
      if (q[2] === p[2] && Math.abs(q[1] - p[1]) < 2) {
        if (q[0] === p[0] - 2) leftHit = true;
        if (q[0] === p[0] + 2) rightHit = true;
      }
    }
    return !(leftHit && rightHit);
  }

  // ---- kinds ------------------------------------------------------------------
  var KINDS = [];
  (function () {
    var i;
    for (i = 1; i <= 9; i++) KINDS.push("d" + i);   // dots
    for (i = 1; i <= 9; i++) KINDS.push("b" + i);   // bamboo
    for (i = 1; i <= 9; i++) KINDS.push("c" + i);   // characters
    KINDS.push("wE", "wS", "wW", "wN", "dR", "dG", "dW");
  })();
  function isFlower(k) { return k[0] === "f"; }
  function isSeason(k) { return k[0] === "s"; }
  function matches(a, b) {
    if (isFlower(a) && isFlower(b)) return true;
    if (isSeason(a) && isSeason(b)) return true;
    return a === b;
  }
  function pairPool(rng) {
    var pairs = [];
    KINDS.forEach(function (k) { pairs.push([k, k], [k, k]); });      // 4 of each
    var fl = shuffle(["f1", "f2", "f3", "f4"], rng);
    var se = shuffle(["s1", "s2", "s3", "s4"], rng);
    pairs.push([fl[0], fl[1]], [fl[2], fl[3]], [se[0], se[1]], [se[2], se[3]]);
    return shuffle(pairs, rng);                                        // 72 pairs
  }

  // deal kinds onto a set of positions so a full solve exists
  function dealOnto(pos, liveIdx, kindsPairs, rng) {
    for (var attempt = 0; attempt < 200; attempt++) {
      var live = new Set(liveIdx);
      var order = [];
      var stuck = false;
      while (live.size) {
        var free = [];
        live.forEach(function (i) { if (isFree(pos, i, live)) free.push(i); });
        if (free.length < 2) { stuck = true; break; }
        shuffle(free, rng);
        var a = free[0], b = free[1];
        order.push([a, b]);
        live.delete(a); live.delete(b);
      }
      if (!stuck) {
        var kinds = {};
        order.forEach(function (pr, i) {
          kinds[pr[0]] = kindsPairs[i][0];
          kinds[pr[1]] = kindsPairs[i][1];
        });
        return kinds;
      }
    }
    return null;
  }

