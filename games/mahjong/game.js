  function freePairs() {
    var free = freeList(), out = [];
    for (var i = 0; i < free.length; i++) {
      for (var j = i + 1; j < free.length; j++) {
        if (matches(kinds[free[i]], kinds[free[j]])) out.push([free[i], free[j]]);
      }
    }
    return out;
  }

