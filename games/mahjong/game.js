  // ---- sound --------------------------------------------------------------------------
  var actx = null;
  function audio() {
    if (!actx) { var AC = window.AudioContext || window.webkitAudioContext; if (AC) actx = new AC(); }
    if (actx && actx.state === "suspended") actx.resume();
    return actx;
  }
  function clack(hi) {
    var ac = audio(); if (!ac) return;
    var t0 = ac.currentTime;
    var len = Math.floor(ac.sampleRate * 0.03), buf = ac.createBuffer(1, len, ac.sampleRate);
    var d = buf.getChannelData(0);
    for (var i = 0; i < len; i++) d[i] = (Math.random() * 2 - 1) * (1 - i / len);
    var src = ac.createBufferSource(); src.buffer = buf;
    var bp = ac.createBiquadFilter(); bp.type = "bandpass"; bp.frequency.value = hi ? 2600 : 1500; bp.Q.value = 2;
    var g = ac.createGain(); g.gain.value = 0.3;
    src.connect(bp); bp.connect(g); g.connect(ac.destination); src.start(t0);
  }
  function thunk() {
    var ac = audio(); if (!ac) return;
    var t0 = ac.currentTime, o = ac.createOscillator(), g = ac.createGain();
    o.type = "sine"; o.frequency.setValueAtTime(160, t0);
    o.frequency.exponentialRampToValueAtTime(90, t0 + 0.08);
    g.gain.setValueAtTime(0.12, t0);
    g.gain.exponentialRampToValueAtTime(0.0001, t0 + 0.1);
    o.connect(g); g.connect(ac.destination); o.start(t0); o.stop(t0 + 0.12);
  }
  function chime() {
    var ac = audio(); if (!ac) return;
    [660, 880, 1174].forEach(function (f, i) {
      var t0 = ac.currentTime + i * 0.1;
      var o = ac.createOscillator(), g = ac.createGain();
      o.type = "triangle"; o.frequency.value = f;
      g.gain.setValueAtTime(0.1, t0);
      g.gain.exponentialRampToValueAtTime(0.0001, t0 + 0.5);
      o.connect(g); g.connect(ac.destination); o.start(t0); o.stop(t0 + 0.55);
    });
  }

  // ---- play -----------------------------------------------------------------------------
  function clickTile(i) {
    // a press while the deal is coming in only lands it; a shuffle still
    // travelling lands, and the press is the press it was
    var coming = dealing;
    settle();
    if (coming) return;
    if (state !== "play" || !live.has(i)) return;
    if (!isFree(pos, i, live)) {
      var el = els[i];
      el.classList.remove("shake"); void el.offsetWidth; el.classList.add("shake");
      // FX off shows .shake as a held red edge (styles.css), so a timer takes it off
      clearTimeout(el.shakeT);
      el.shakeT = setTimeout(function () { el.classList.remove("shake"); }, 450);
      thunk();
      return;
    }
    if (selected === i) { els[i].classList.remove("sel"); selected = -1; return; }
    if (selected >= 0 && matches(kinds[selected], kinds[i])) {
      removePair(selected, i);
      return;
    }
    if (selected >= 0) els[selected].classList.remove("sel");
    selected = i;
    els[i].classList.add("sel");
    clack(true);
  }
  function removePair(a, b) {
    els[a].classList.remove("sel");
    live.delete(a); live.delete(b);
    sendOff(els[a], els[b]);
    delete els[a]; delete els[b];
    undoStack.push([a, b]);
    selected = -1;
    clack(false);
    refreshFreedom();
    hud();
    if (!live.size) { win(); return; }
    if (!freePairs().length) hint(true);   // nudge: no moves, suggests shuffle
  }
  function undo() {
    if (state !== "play" || !undoStack.length) return;
    settle();
    var pr = undoStack.pop();
    penaltyMs += 15000;
    dead = false;                      // a pair back on the board: there's a way on again
    pr.forEach(function (i) {
      live.add(i);
      var b = document.createElement("button");
      b.type = "button"; b.className = "tile";
      (function (idx) { b.addEventListener("click", function () { clickTile(idx); }); })(i);
      $("board").appendChild(b);
      els[i] = b;
    });
    if (selected >= 0) { els[selected] && els[selected].classList.remove("sel"); selected = -1; }
    layout();
    hud();
    clack(true);
  }
  function hint(isNudge) {
    if (state !== "play") return;
    settle();
    var prs = freePairs();
    if (!prs.length) {
      // nothing matches: point at the shuffle, or at Undo when no reshuffle
      // can fit what's left (a lone stack, say)
      if (redeal()) pointAt("btn-shuffle");
      else noRedeal();
      if (!isNudge) thunk();
      return;
    }
    if (!isNudge) penaltyMs += 30000;
    var pr = prs[Math.floor(Math.random() * prs.length)];
    pr.forEach(function (i) {
      var el = els[i];
      el.classList.remove("hintg"); void el.offsetWidth; el.classList.add("hintg");
      // FX off holds the glow still (styles.css): it comes off once the two
      // 0.8s pulses would have finished
      clearTimeout(el.hintT);
      el.hintT = setTimeout(function () { el.classList.remove("hintg"); }, 1650);
    });
    hud();
  }
  // a HUD button outlined for a moment: "try this"
  function pointAt(id) {
    var b = $(id);
    b.style.outline = "3px solid #ffd23f";
    clearTimeout(b.pointT);
    b.pointT = setTimeout(function () { b.style.outline = ""; }, 1200);
  }
  // the remaining kinds regrouped into matchable pairs and re-dealt solvably
  // onto the same spots; null when no solvable deal fits them
  function redeal() {
    var rem = [];
    live.forEach(function (i) { rem.push(kinds[i]); });
    var groups = {};
    rem.forEach(function (k) {
      var g = isFlower(k) ? "F" : isSeason(k) ? "S" : k;
      (groups[g] = groups[g] || []).push(k);
    });
    var pairs = [];
    Object.keys(groups).forEach(function (g) {
      var arr = groups[g];
      for (var i = 0; i + 1 < arr.length; i += 2) pairs.push([arr[i], arr[i + 1]]);
    });
    var rng = Math.random;
    shuffle(pairs, rng);
    return dealOnto(pos, [...live], pairs, rng);
  }
  // no reshuffle fits: the board is dead. Taking a pair back is the way on;
  // the HUD offers a new deal too (hud())
  function noRedeal() {
    dead = true;
    pointAt("btn-undo");
    hud();
  }
  function reshuffle() {
    if (state !== "play" || (live.size < 4 && freePairs().length)) return;
    settle();
    var dealt = redeal(), was = kinds;
    if (!dealt) {
      // the board stays, and it costs nothing
      thunk();
      noRedeal();
      return;
    }
    penaltyMs += 60000;
    kinds = Object.assign({}, kinds, dealt);
    if (selected >= 0 && els[selected]) els[selected].classList.remove("sel");   // its face just changed
    selected = -1;
    layout();
    shuffleIn(was);
    hud();
    clack(false);
  }

