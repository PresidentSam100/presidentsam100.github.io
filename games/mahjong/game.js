  // a little picture of a layout, seen as the board is: each tile a chip, the
  // higher layers paler and set up and to the right
  function drawLayout(cv, l) {
    var box = cv.getBoundingClientRect(), dpr = Math.min(2, window.devicePixelRatio || 1);
    var W = Math.round(box.width) || 96, H = Math.round(box.height) || 68;
    if (cv.width !== W * dpr || cv.height !== H * dpr) { cv.width = W * dpr; cv.height = H * dpr; }
    var g = cv.getContext("2d");
    g.setTransform(dpr, 0, 0, dpr, 0, 0);
    g.clearRect(0, 0, W, H);
    var zo = 1.5, u = (W - 4 * zo - 1) / 15, v = (H - 4 * zo - 1) / 8;
    var SHADE = ["#cdbb93", "#dccdaa", "#e9dec2", "#f4ecd8", "#fffaf0"];
    l.make().sort(function (a, b) { return a[2] - b[2] || a[1] - b[1] || a[0] - b[0]; }).forEach(function (p) {
      var x = p[0] * u / 2 + p[2] * zo, y = p[1] * v / 2 + (4 - p[2]) * zo;
      g.fillStyle = "#7a6238";
      g.fillRect(x, y + 1, u, v);
      g.fillStyle = SHADE[p[2]];
      g.fillRect(x + 1, y, u - 0.6, v - 0.6);
    });
  }
