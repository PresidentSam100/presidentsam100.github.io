/* =====================================================================
   Mahjong — the tile-matching solitaire, dealt winnable.

   The classic 144-tile Turtle. A tile is free when nothing rests on it
   and its left OR right flank is open; remove matching free pairs
   (flowers match any flower, seasons any season) until the desk is
   clear. Boards are generated by simulating a solve on blank tiles and
   assigning kinds to the removed pairs, so every deal can be finished.

   Coordinates: doubled grid (gx, gy) so half-step tiles (the turtle's
   head and the apex) stay integers; a tile spans 2x2 cells on layer z.
   ===================================================================== */
