  function layoutNow() { return mode === "daily" ? dailyLayout(today().n) : layoutBy(layoutId); }
  var dealt = LAYOUTS[0], pos = dealt.make();
  var kinds = {}, live = new Set(), els = {};
  var selected = -1, undoStack = [], timeMs = 0, penaltyMs = 0;
